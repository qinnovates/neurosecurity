#!/usr/bin/env node
/**
 * Writes the purpose and limits statement into the markdown files that carry it,
 * from the single source in src/data/purpose-and-limits.json. The site renders the
 * same JSON through src/lib/purpose-and-limits.ts, so the wording lives in one place.
 *
 * Each target holds a generated block between BEGIN/END markers; text outside the
 * markers is left alone.
 *
 * Usage: node src/scripts/generate-purpose-and-limits.mjs [--check]
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '../..');
const SOURCE_PATH = resolve(ROOT, 'src/data/purpose-and-limits.json');
const REPO_BLOB_URL = 'https://github.com/qinnovates/neurosecurity/blob/main';
const BEGIN = (block) => `<!-- BEGIN purpose-and-limits:${block} (generated by npm run purpose:sync from src/data/purpose-and-limits.json; do not edit) -->`;
const END = (block) => `<!-- END purpose-and-limits:${block} -->`;

const statement = JSON.parse(readFileSync(SOURCE_PATH, 'utf8'));
const { links, purposeAndLimits } = statement;
const canonicalUrl = `${REPO_BLOB_URL}/governance/README.md#${purposeAndLimits.anchor}`;

function absoluteUrl(href) {
  return href.startsWith('http') ? href : `${links.siteOrigin}${href}`;
}

function renderSegments(segments) {
  return segments
    .map((segment) => (segment.link ? `[${segment.text}](${absoluteUrl(links[segment.link])})` : segment.text))
    .join('');
}

const BLOCKS = {
  canonical: () => [
    `## ${purposeAndLimits.heading}`,
    '',
    ...purposeAndLimits.sections.flatMap((section) => [`**${section.label}** ${renderSegments(section.segments)}`, '']),
  ].join('\n').trimEnd(),
  summary: () => `${statement.summary} [Purpose and limits](${canonicalUrl}).`,
  security: () => [
    statement.oneSentence,
    '',
    statement.securityPreamble,
    '',
    `See [Purpose and limits](${canonicalUrl}).`,
  ].join('\n'),
};

const TARGETS = [
  { path: 'governance/README.md', block: 'canonical' },
  { path: 'README.md', block: 'summary' },
  { path: 'datalake/qtara/README.md', block: 'summary' },
  { path: 'SECURITY.md', block: 'security' },
  { path: 'governance/SECURITY.md', block: 'security' },
];

function regenerate(document, block, path) {
  const begin = BEGIN(block);
  const end = END(block);
  const start = document.indexOf(begin);
  const stop = document.indexOf(end);
  if (start === -1 || stop === -1 || stop < start) {
    throw new Error(`[purpose-and-limits] ${path}: markers for block "${block}" are missing or out of order. Restore the BEGIN/END comments, then rerun npm run purpose:sync.`);
  }
  return `${document.slice(0, start)}${begin}\n${BLOCKS[block]()}\n${document.slice(stop)}`;
}

const isCheck = process.argv.includes('--check');
const stale = [];
try {
  for (const target of TARGETS) {
    const fullPath = resolve(ROOT, target.path);
    const document = readFileSync(fullPath, 'utf8');
    const updated = regenerate(document, target.block, target.path);
    if (updated === document) continue;
    if (isCheck) stale.push(target.path);
    else writeFileSync(fullPath, updated);
  }
} catch (error) {
  console.error(error instanceof Error ? error.message : error);
  process.exit(1);
}

if (isCheck && stale.length > 0) {
  console.error(`[purpose-and-limits] stale copies: ${stale.join(', ')}. Run: npm run purpose:sync`);
  process.exit(1);
}
console.log(`[purpose-and-limits] ${isCheck ? 'all copies current' : 'copies written'} (${TARGETS.length} files).`);
