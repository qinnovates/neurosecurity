#!/usr/bin/env node
/**
 * Writes docs/atlas/INDEX.md and docs/atlas/FOLLOW-UPS.md from the atlas map.
 * The map is the source of truth; these pages are a view of it for people.
 *
 * Usage: node src/scripts/atlas-map/render-atlas-docs.mjs [--check]
 *   --check  write nothing; exit 1 if either page differs from the map.
 */

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { ATLAS_MAP_FILE, OWNERS } from './parse-atlas-map.mjs';
import { REPOSITORY_ROOT, loadAtlasMap } from './load-atlas-map.mjs';

export const INDEX_FILE = 'docs/atlas/INDEX.md';
export const FOLLOWUPS_FILE = 'docs/atlas/FOLLOW-UPS.md';
const BANNER = `<!-- Generated by npm run atlas:docs from ${ATLAS_MAP_FILE}. Do not edit; edit the map. -->`;
const OWNER_HEADINGS = { kevin: 'Kevin', data: 'Data', engineering: 'Engineering', 'domain-review': 'Domain review' };

const cell = (text) => text.replace(/[\\|]/g, '\\$&');
const code = (text) => `\`${text}\``;
const codeList = (items) => (items.length === 0 ? '-' : items.map(code).join(', '));
const pending = (record) => (record.pending_pr === undefined ? '' : ` (pending #${record.pending_pr})`);
const table = (header, rows) => [`| ${header.join(' | ')} |`, `|${header.map(() => '---').join('|')}|`, ...rows.map((row) => `| ${row.map(cell).join(' | ')} |`)];

function renderModules(map) {
  return ['## Modules', '', 'Imports point down the `depends_on` column only. Rules that never bend, and the recipes, are in `src/lib/anatomy/CONTEXT.md`.', '',
    ...table(['Id', 'Directory', 'Responsibility', 'Map', 'Entry files', 'Depends on'], map.modules.map((module) => [
      module.id, code(module.path) + pending(module), module.responsibility, code(module.map_file), codeList(module.entry_files), module.depends_on.join(', ') || '-',
    ]))];
}

function renderData(map) {
  return ['## Data files', '',
    ...table(['Id', 'File', 'Holds', 'Validated by', 'Written by', 'Read by'], map.data.map((data) => [
      data.id, code(data.path) + pending(data), data.holds, code(data.validated_by), data.generator === 'source' ? 'hand (source)' : code(data.generator), data.consumers.join(', ') || '-',
    ]))];
}

function renderChecks(map) {
  return ['## Checks', '',
    ...table(['Id', 'Script', 'Guards', 'CI'], map.checks.map((check) => [
      check.id, code(`npm run ${check.script}`) + pending(check), check.guards, check.ci === null ? 'not in CI' : `${code(check.ci.workflow)} job ${code(check.ci.job)}`,
    ]))];
}

function renderChanges(map) {
  const recipe = (change) => (change.recipe === null ? '-' : `${code(change.recipe.map)} recipe ${change.recipe.number}`);
  return ['## Where do I change X', '', 'Or run `npm run atlas:where -- <words>` for one entry with its commands and checks.', '',
    ...table(['Request', 'Recipe', 'Edit', 'Then run'], map.changes.map((change) => [
      change.summary + pending(change), recipe(change), codeList(change.edit), codeList(change.commands),
    ]))];
}

function renderProvenance(map) {
  return ['## Provenance', '', 'Archived copies of the documents that justify shipped data. The build spec stays in staging (`<staging>/2026-10-atlas-geometry/build-spec.md`).', '',
    ...table(['Document', 'Justifies'], map.provenance.map((record) => [code(record.path), record.justifies]))];
}

/** @param {import('./parse-atlas-map.d.mts').AtlasMap} map */
export function renderIndex(map) {
  const openCount = map.followups.filter((followup) => followup.status === 'open').length;
  return [BANNER, '# TARA Brain Atlas and framing: index', '',
    `Start here for anything atlas, anatomy, brain view, DSM wording or purpose-and-limits. Quickest lookup: \`npm run atlas:where -- <words>\`. The source of truth is \`${ATLAS_MAP_FILE}\`; this page is generated from it and states structure only. PR state and merge order live in the planning epic; the ${openCount} open items are in \`${FOLLOWUPS_FILE}\`.`, '',
    'Paths are from the repository root. "(pending #N)" marks a record whose files live on that open framing PR, not yet here.', '',
    '## What it is', '', map.summary, '',
    ...renderModules(map), '', ...renderData(map), '', ...renderChecks(map), '', ...renderChanges(map), '', ...renderProvenance(map), ''].join('\n');
}

function renderFollowupLine(followup) {
  const box = followup.status === 'done' ? 'x' : ' ';
  return `- [${box}] **${followup.id}**: ${followup.what} Ref: ${followup.ref}. From: ${followup.from}.`;
}

/** @param {import('./parse-atlas-map.d.mts').AtlasMap} map */
export function renderFollowups(map) {
  const sections = OWNERS.flatMap((owner) => {
    const items = map.followups.filter((followup) => followup.owner === owner);
    const open = items.filter((followup) => followup.status === 'open').length;
    return items.length === 0 ? [] : [`## ${OWNER_HEADINGS[owner]} (${open} open)`, '', ...items.map(renderFollowupLine), ''];
  });
  return [BANNER, '# TARA Brain Atlas and framing: follow-ups and decisions', '',
    `Generated from the \`followups\` section of \`${ATLAS_MAP_FILE}\`. To add, close or re-own an item, edit the map and run \`npm run atlas:docs\`. Ids are never reused or renumbered; close an item by setting its status to done and naming the PR in its text.`, '',
    ...sections].join('\n');
}

/** Each generated page with the text the map says it should hold. */
export function renderAll(map) {
  return [[INDEX_FILE, renderIndex(map)], [FOLLOWUPS_FILE, renderFollowups(map)]];
}

/** The pages whose committed text differs from the map. */
export function findStalePages(map, root = REPOSITORY_ROOT) {
  return renderAll(map).filter(([file, text]) => {
    const target = path.join(root, file);
    return !fs.existsSync(target) || fs.readFileSync(target, 'utf-8') !== text;
  }).map(([file]) => file);
}

function main(argv) {
  const map = loadAtlasMap();
  if (argv.includes('--check')) {
    const stale = findStalePages(map);
    if (stale.length === 0) return 0;
    process.stderr.write(`Out of date with ${ATLAS_MAP_FILE}: ${stale.join(', ')}. Run npm run atlas:docs and commit the result.\n`);
    return 1;
  }
  for (const [file, text] of renderAll(map)) fs.writeFileSync(path.join(REPOSITORY_ROOT, file), text);
  process.stdout.write(`Wrote ${INDEX_FILE} and ${FOLLOWUPS_FILE}.\n`);
  return 0;
}

const isRunDirectly = process.argv[1] !== undefined
  && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url);

if (isRunDirectly) process.exitCode = main(process.argv.slice(2));
