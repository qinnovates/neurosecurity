#!/usr/bin/env node
/**
 * Writes src/site/_headers from src/lib/csp-policy.ts, so the preview host's response
 * headers can never drift from the policy metas the layouts render.
 *
 * The file is read by the Cloudflare Pages preview only. Production is GitHub Pages,
 * which sends no custom header; there the layouts' metas are the whole policy.
 *
 * Usage:
 *   node src/scripts/generate-headers.mjs           # write the file (prebuild)
 *   node src/scripts/generate-headers.mjs --check   # exit 1 when the committed file differs
 *
 * QINNOVATE_PREVIEW=1 adds X-Robots-Tag, so a preview build is never indexed even when a
 * page's own robots meta is missing.
 */

import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import {
  ISOLATED_POLICY,
  PERMISSIONS_POLICY,
  SITE_PAGE_CSP,
  TOOL_PAGE_PATH_PATTERNS,
  joinPolicy,
} from '../lib/csp-policy.ts';

const SCRIPT_DIRECTORY = path.dirname(fileURLToPath(import.meta.url));
export const HEADERS_FILE = path.resolve(SCRIPT_DIRECTORY, '../site/_headers');
export const PREVIEW_FLAG = 'QINNOVATE_PREVIEW';
const CSP_HEADER = 'Content-Security-Policy';
const ROBOTS_HEADER = 'X-Robots-Tag: noindex, nofollow';

const COMMON_HEADERS = [
  'X-Frame-Options: SAMEORIGIN',
  'X-Content-Type-Options: nosniff',
  'Referrer-Policy: strict-origin-when-cross-origin',
  `Permissions-Policy: ${PERMISSIONS_POLICY}`,
  'Strict-Transport-Security: max-age=31536000; includeSubDomains',
];

function renderBlock(pattern, headerLines) {
  return [pattern, ...headerLines.map((line) => `  ${line}`)].join('\n');
}

/**
 * The whole file as text.
 * @param {{ preview?: boolean }} options preview adds the robots header to every response
 */
export function renderHeaders({ preview = false } = {}) {
  const siteHeaders = [
    ...COMMON_HEADERS,
    ...(preview ? [ROBOTS_HEADER] : []),
    `${CSP_HEADER}: ${joinPolicy(SITE_PAGE_CSP)}`,
  ];
  const blocks = [
    '# Generated by src/scripts/generate-headers.mjs from src/lib/csp-policy.ts; do not edit by hand.',
    '# Read by the Cloudflare preview host only. Production (GitHub Pages) sends no custom header.',
    renderBlock('/*', siteHeaders),
    ...TOOL_PAGE_PATH_PATTERNS.map((pattern) => renderBlock(pattern, [`${CSP_HEADER}: ${ISOLATED_POLICY}`])),
  ];
  return `${blocks.join('\n')}\n`;
}

function isPreviewBuild(env = process.env) {
  return env[PREVIEW_FLAG] === '1';
}

function main(argv) {
  const text = renderHeaders({ preview: isPreviewBuild() });
  if (argv.includes('--check')) {
    let current = '';
    try {
      current = readFileSync(HEADERS_FILE, 'utf-8');
    } catch (error) {
      const detail = error instanceof Error ? error.message : String(error);
      process.stderr.write(`[generate-headers] cannot read ${path.relative(process.cwd(), HEADERS_FILE)} (${detail}); run "npm run headers:generate".\n`);
      process.exitCode = 1;
      return;
    }
    if (current !== text) {
      process.stderr.write(`[generate-headers] ${path.relative(process.cwd(), HEADERS_FILE)} differs from csp-policy.ts; run "npm run headers:generate" and commit the result.\n`);
      process.exitCode = 1;
      return;
    }
    process.stdout.write('[generate-headers] _headers matches csp-policy.ts\n');
    return;
  }
  writeFileSync(HEADERS_FILE, text);
  process.stdout.write(`[generate-headers] wrote ${path.relative(process.cwd(), HEADERS_FILE)}${isPreviewBuild() ? ' (preview: noindex)' : ''}\n`);
}

const isRunDirectly = process.argv[1] !== undefined && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url);
if (isRunDirectly) main(process.argv.slice(2));
