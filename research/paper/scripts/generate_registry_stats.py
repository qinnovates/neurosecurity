#!/usr/bin/env python3
"""Emit LaTeX macros for every registry figure the paper quotes.

The paper carried five different technique counts and two different values for
the same gap percentage, because each figure was typed by hand into whichever
file needed it and then drifted. Numbers the registry can answer are defined
here once and used as macros, so a stale figure becomes a build-time
impossibility rather than something a reader has to catch.

Two distinct sets of figures are emitted, and they must not be confused:

  \\Snapshot...  the registry v1.5 state the paper's own analysis was computed
                against. These are frozen literals. The published analysis
                (severity distributions, DSM clusters, consent tiers,
                therapeutic-analog counts) has numerators derived from that
                set, so the denominator cannot be updated without recomputing
                every numerator. A published analysis gets versioned, not
                silently re-pointed at newer data.

  \\Live...      the current registry, read from the source of truth at build
                time. Use these only where the text is explicitly talking about
                the registry as it stands now.

Usage:
    python3 generate_registry_stats.py          # writes ../generated/registry-stats.tex
    python3 generate_registry_stats.py --check  # exit 1 if the file is stale
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

PAPER_DIR = Path(__file__).resolve().parent.parent
REPO_ROOT = PAPER_DIR.parent.parent
REGISTRY = REPO_ROOT / "datalake" / "qtara-registrar.json"
OUTPUT = PAPER_DIR / "generated" / "registry-stats.tex"

# The registry state the paper's published analysis was computed against.
# Frozen deliberately: every derived numerator in sections 4 to 7 is relative
# to these, so they are part of the paper, not of the live data.
SNAPSHOT = {
    "SnapshotRegistryVersion": "1.5",
    "SnapshotTechniques": "109",
    "SnapshotTactics": "15",
    "SnapshotDomains": "8",
    "SnapshotGapTechniques": "108",
    "SnapshotGapPercent": "99.1",
}


def live_macros(registry: dict) -> dict[str, str]:
    """The figures the live registry can answer, as macro name to value."""
    stats = registry["statistics"]
    techniques = registry["techniques"]
    total = len(techniques)
    if total != stats["total_techniques"]:
        raise SystemExit(
            f"registry is internally inconsistent: statistics.total_techniques="
            f"{stats['total_techniques']} but the techniques array holds {total}"
        )

    gap_groups = stats["niss_cvss_mapping"]["by_gap_group"]
    gap_total = sum(gap_groups.values())
    scoring = stats["by_scoring_state"]
    scoring_total = sum(scoring.values())
    if scoring_total != total:
        raise SystemExit(
            f"by_scoring_state sums to {scoring_total}, not the {total} techniques present"
        )

    with_cvss = sum(1 for technique in techniques if technique.get("cvss"))

    return {
        "LiveRegistryVersion": str(registry["version"]),
        "LiveTechniques": str(total),
        "LiveVariants": str(stats["total_variants"]),
        "LiveTactics": str(stats["total_tactics"]),
        "LiveWithCvss": str(with_cvss),
        "LiveNissScored": str(scoring["scored"]),
        "LiveNissProvisional": str(scoring["provisional"]),
        "LiveNissUnscored": str(scoring["unscored"]),
        "LiveGapTechniques": str(gap_total),
        "LiveGapPercent": f"{gap_total / total * 100:.1f}",
        "LivePinsFlagged": str(stats["niss_cvss_mapping"]["pins_flagged"]),
    }


def render(macros: dict[str, str]) -> str:
    lines = [
        "% Generated by research/paper/scripts/generate_registry_stats.py",
        "% Do not edit. Run `make stats` in research/paper/ to regenerate.",
        "%",
        "% Snapshot* are the frozen registry v1.5 figures the paper's analysis was",
        "% computed against. Live* are read from datalake/qtara-registrar.json at",
        "% build time. Do not use a Live* macro as the denominator of a numerator",
        "% that was computed over the snapshot.",
        "",
    ]
    # No padding inside the braces: a macro body is emitted verbatim, so a
    # trailing space for alignment would print as a space in the PDF.
    for name, value in macros.items():
        lines.append(f"\\newcommand{{\\{name}}}{{{value}}}")
    lines.append("")
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="exit 1 if the output is stale")
    args = parser.parse_args()

    registry = json.loads(REGISTRY.read_text())
    macros = {**SNAPSHOT, **live_macros(registry)}
    rendered = render(macros)

    if args.check:
        if not OUTPUT.exists():
            print(f"{OUTPUT.relative_to(REPO_ROOT)} does not exist; run `make stats`", file=sys.stderr)
            return 1
        if OUTPUT.read_text() != rendered:
            print(
                f"{OUTPUT.relative_to(REPO_ROOT)} is stale against the registry; run `make stats`",
                file=sys.stderr,
            )
            return 1
        print(f"{OUTPUT.relative_to(REPO_ROOT)} is current")
        return 0

    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text(rendered)
    print(f"wrote {OUTPUT.relative_to(REPO_ROOT)}")
    for name, value in macros.items():
        print(f"  \\{name} = {value}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
